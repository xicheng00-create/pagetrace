def expand(query: str) -> set[str]:
    """把 query 里出现的口语键，换成术语片段集合。没有命中就返回空集（主臂照旧）。"""
    text = query or ""
    targets: set[str] = set()
    for key, values in ALIASES.items():
        if key in text:
            targets.update(values)
    return targets
