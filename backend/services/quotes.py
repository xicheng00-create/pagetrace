def quote_index(day: date, size: int | None = None) -> int:
    """当天格言索引：`(day - QUOTE_EPOCH).days % size`。size≤0 → 0（不除零）。"""
    size = len(QUOTES) if size is None else size
    if size <= 0:
        return 0
    return (day - QUOTE_EPOCH).days % size


def quote_for(day: date, quotes: list[str] | None = None) -> dict:
    """返回 {"id", "text", "total"}。列表为空 → 回落文案（id=None），不空白、不编造。"""
    q = QUOTES if quotes is None else quotes
    total = len(q)
    if total <= 0:
        return {"id": None, "text": FALLBACK_TEXT, "total": 0}
    idx = quote_index(day, total)
    return {"id": idx, "text": q[idx], "total": total}


def today_quote(at=None) -> dict:
    """按本地日（东八区）取当天格言（同一自然日恒定）。"""
    day = (at or now()).date()
    return quote_for(day)
